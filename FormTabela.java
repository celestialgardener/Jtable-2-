    private void btnSalvarProdutoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarProdutoActionPerformed
        // TODO add your handling code here:
        
        // aqui lembre de importar : javax.swing.table.DefaultTableModel, se voce estiver fazendo isso
        //no netbeans clique na lampada que ele ja importa la em cima
        //pegar os dados do form
        
        String codigo = txtCodigo.getText();
        String nome = txtNome.getText();
        String valor = txtValor.getText();
        String quantia = txtQuantia.getText();
        
        // agora criar uma tabela 
        DefaultTableModel tabelaProduto = (DefaultTableModel) tblProdutos.getModel(); //esse getmodel pega o modelo da tabela jtable
        
        
        //agora crie um array de objetos na mesma ordem que os campos na tabela
        Object[] novoProduto = new Object[]{
            codigo, //pos 1 do array
            nome, //pos 2 
            valor,
            quantia,
            
    };
        //com isso feito passe esses valores pra tabela com o metodo abaixo 
        tabelaProduto.addRow(novoProduto);
        //depois disso limpe os campos de texto
        txtCodigo.setText("");
        txtNome.setText("");
        txtValor.setText("");
        txtQuantia.setText("");
    }//GEN-LAST:event_btnSalvarProdutoActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        //esse botão exclui linhas
        //primeiro tem que ver se tem uma linha selecionada na tabela, e descobrir o numero da linha selecionada
        //a primeira linha e a zero ja que estamos usando um array
        int linhaSelecionada = tblProdutos.getSelectedRow(); // aqui se nehuma linha estiver selecionada retorna -1
        if (linhaSelecionada == -1){
            //lembre de importar joptionpane
            JOptionPane.showMessageDialog(this,"selecione uma linha"); //o parametro this se refere a esse formulario
        }else{
        DefaultTableModel tabelaProduto = (DefaultTableModel) tblProdutos.getModel();
        tabelaProduto.removeRow(linhaSelecionada); //recebe int como parametro e deleta a linha
        JOptionPane.showMessageDialog(this,"linha excluida");
        }
        
    }//GEN-LAST:event_btnExcluirActionPerformed

